"""
File storage.

`ObjectStorage` is the interface the rest of the app uses. `SupabaseStorage`
talks to Supabase Storage's REST API directly with httpx (no heavy SDK).
Tests use an in-memory fake with the same three methods.

Paths are always generated by the server (UUIDs + random suffixes), never
taken from user input, so there is no path traversal to worry about.
"""

import logging
from pathlib import Path
from typing import Protocol

import httpx

from app.core.errors import ServiceUnavailableError

logger = logging.getLogger("app.storage")


class ObjectStorage(Protocol):
    def upload(self, path: str, local_file: Path, content_type: str) -> None: ...

    def download(self, path: str, local_file: Path) -> None: ...

    def delete(self, paths: list[str]) -> None: ...


class StorageError(ServiceUnavailableError):
    code = "storage_unavailable"
    message = "File storage is temporarily unavailable. Please retry."


class SupabaseStorage:
    def __init__(self, supabase_url: str, secret_key: str, bucket: str, *, transport: httpx.BaseTransport | None = None) -> None:
        headers = {"apikey": secret_key}
        # New sb_secret_ keys go ONLY in the apikey header (they are not JWTs).
        # Legacy service_role keys are JWTs and also need the Authorization header.
        if secret_key.startswith("eyJ"):
            headers["Authorization"] = f"Bearer {secret_key}"
        self._bucket = bucket
        self._client = httpx.Client(
            base_url=f"{supabase_url}/storage/v1",
            headers=headers,
            timeout=httpx.Timeout(60.0, connect=5.0),
            transport=transport,
        )

    def close(self) -> None:
        self._client.close()

    def upload(self, path: str, local_file: Path, content_type: str) -> None:
        def send() -> httpx.Response:
            with open(local_file, "rb") as handle:
                return self._client.post(
                    f"/object/{self._bucket}/{path}",
                    content=handle,
                    headers={"Content-Type": content_type, "x-upsert": "false", "Cache-Control": "no-store"},
                )

        response = self._with_retry(send, f"upload {path}")
        # 409 on the retry means the first attempt actually succeeded.
        if response.status_code == 409:
            return
        self._raise_for(response, f"upload {path}")

    def download(self, path: str, local_file: Path) -> None:
        def send() -> httpx.Response:
            with self._client.stream("GET", f"/object/authenticated/{self._bucket}/{path}") as response:
                if response.status_code == 200:
                    with open(local_file, "wb") as handle:
                        for chunk in response.iter_bytes(1024 * 1024):
                            handle.write(chunk)
                else:
                    response.read()
                return response

        response = self._with_retry(send, f"download {path}")
        self._raise_for(response, f"download {path}")

    def delete(self, paths: list[str]) -> None:
        if not paths:
            return
        for start in range(0, len(paths), 100):
            batch = paths[start : start + 100]
            response = self._with_retry(
                lambda batch=batch: self._client.request("DELETE", f"/object/{self._bucket}", json={"prefixes": batch}),
                "delete",
            )
            self._raise_for(response, "delete")

    # ------------------------------------------------------------------
    def _with_retry(self, send, what: str) -> httpx.Response:
        last_error: Exception | None = None
        for attempt in (1, 2):
            try:
                response = send()
                if response.status_code < 500 or attempt == 2:
                    return response
                logger.warning("storage %s got %s, retrying", what, response.status_code)
            except httpx.TransportError as exc:
                last_error = exc
                logger.warning("storage %s transport error (attempt %d): %s", what, attempt, type(exc).__name__)
        raise StorageError() from last_error

    @staticmethod
    def _raise_for(response: httpx.Response, what: str) -> None:
        if response.status_code >= 300:
            # Log status and a short body; never log headers (they contain the key).
            logger.error("storage %s failed: %s %s", what, response.status_code, response.text[:200])
            raise StorageError()
