"""
Render the report as an editable Word document (same content as the HTML).

Word has no Manrope, so the template uses Calibri / Consolas, which every
Office install has, in the Sage colours. Charts are not embedded (that would
need an image library on a 512 MB server); each profile lists its numbers and
top values instead, and the HTML report carries the charts.
"""

import io

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Mm, Pt, RGBColor

TEXT = RGBColor(0x1E, 0x26, 0x20)
MUTED = RGBColor(0x59, 0x64, 0x5B)
ACCENT = RGBColor(0x2B, 0x4E, 0x37)
WARN = RGBColor(0x85, 0x5A, 0x0C)
HEADER_FILL = "E2ECE3"
LINE = "DCE2D8"
SANS, MONO = "Calibri", "Consolas"


def _shade(cell, fill: str) -> None:
    props = cell._tc.get_or_add_tcPr()
    shading = OxmlElement("w:shd")
    shading.set(qn("w:val"), "clear")
    shading.set(qn("w:color"), "auto")
    shading.set(qn("w:fill"), fill)
    props.append(shading)


def _borders(table) -> None:
    props = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "nil" if edge == "insideV" else "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), LINE)
        borders.append(el)
    props.append(borders)


def _repeat_header(row) -> None:
    props = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    props.append(el)


def _run(paragraph, text: str, *, bold=False, color=None, mono=False, size=None):
    run = paragraph.add_run(text)
    run.bold = bold
    if color is not None:
        run.font.color.rgb = color
    if mono:
        run.font.name = MONO
        run._element.rPr.rFonts.set(qn("w:eastAsia"), MONO)
    if size:
        run.font.size = Pt(size)
    return run


def _table(doc, header: list[str], rows: list[list[str]], right: set[int] = frozenset(), mono: set[int] = frozenset(), widths=None):
    table = doc.add_table(rows=1, cols=len(header))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    _borders(table)
    _repeat_header(table.rows[0])
    for i, label in enumerate(header):
        cell = table.rows[0].cells[i]
        _shade(cell, HEADER_FILL)
        p = cell.paragraphs[0]
        _run(p, label, bold=True, color=ACCENT, size=9)
        if i in right:
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    for values in rows:
        cells = table.add_row().cells
        for i, value in enumerate(values):
            p = cells[i].paragraphs[0]
            _run(p, str(value), mono=i in mono, size=9)
            if i in right:
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    if widths:
        table.autofit = False
        for row in table.rows:
            for i, width in enumerate(widths):
                row.cells[i].width = Mm(width)
    doc.add_paragraph()
    return table


def _heading(doc, index: str, text: str) -> None:
    p = doc.add_heading(level=1)
    _run(p, f"{index}  ", color=RGBColor(0x3F, 0x6E, 0x4E), mono=True, size=12)
    _run(p, text, color=TEXT)


def _setup(doc) -> None:
    section = doc.sections[0]
    section.page_width, section.page_height = Mm(210), Mm(297)
    for side in ("left_margin", "right_margin"):
        setattr(section, side, Mm(18))
    section.top_margin, section.bottom_margin = Mm(16), Mm(16)

    normal = doc.styles["Normal"]
    normal.font.name = SANS
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), SANS)
    normal.font.size = Pt(10.5)
    normal.font.color.rgb = TEXT
    normal.paragraph_format.space_after = Pt(4)
    for name, size in (("Heading 1", 16), ("Heading 2", 12.5), ("Title", 26)):
        style = doc.styles[name]
        style.font.name = SANS
        style.element.rPr.rFonts.set(qn("w:eastAsia"), SANS)
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = TEXT
        style.paragraph_format.space_before = Pt(14 if name != "Title" else 0)
        style.paragraph_format.space_after = Pt(6)

    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER


def render_docx(r: dict) -> bytes:
    doc = Document()
    _setup(doc)
    meta = r["meta"]
    _run(doc.sections[0].footer.paragraphs[0], f"Generated by {meta['app']} · {meta['generated_display']} · {meta['dataset_name']} v{meta['version']}", color=MUTED, size=8)

    # ---- cover
    p = doc.add_paragraph()
    _run(p, meta["app"], bold=True, color=ACCENT, size=12)
    for _ in range(6):
        doc.add_paragraph()
    p = doc.add_paragraph()
    _run(p, "DATA ANALYSIS REPORT", bold=True, color=MUTED, size=9)
    doc.add_paragraph(meta["title"], style="Title")
    details = []
    if meta.get("author"):
        details.append(("Prepared by", meta["author"]))
    details += [("Dataset", meta["dataset_name"]),
                ("Source file", f"{meta['source_filename']} · {meta['source_format']} · {meta['source_size']}")]
    if meta.get("sheet_name"):
        details.append(("Sheet", meta["sheet_name"] + (f" (1 of {meta['sheet_count']})" if meta.get("sheet_count") else "")))
    details += [("Version reported", f"v{meta['version']}"), ("Generated", meta["generated_display"])]
    for label, value in details:
        p = doc.add_paragraph()
        _run(p, f"{label}:  ", color=MUTED)
        _run(p, value, bold=True)
    doc.add_page_break()

    # ---- 1 summary
    _heading(doc, "01", "Summary")
    _table(doc, [k["label"] for k in r["summary"]["kpis"]],
           [[k["value"] + (f" ({k['hint']})" if k.get("hint") else "") for k in r["summary"]["kpis"]]],
           mono={0, 1, 2, 3})
    doc.add_heading("Key findings", level=2)
    for finding in r["summary"]["findings"]:
        doc.add_paragraph(finding, style="List Bullet")

    # ---- 2 the data
    _heading(doc, "02", "The data")
    d = r["dataset"]
    types = ", ".join(f"{t['count']} {t['label']}" for t in d["types"])
    doc.add_paragraph(f"{d['rows']} rows × {d['columns']} columns ({d['cells']} cells). Types: {types}.")
    doc.add_heading("Data dictionary", level=2)
    _table(doc, ["Column", "Type", "Role", "Missing", "Unique", "Values"],
           [[c["name"], c["dtype"], c["role"], c["missing"], c["unique"], c["summary"]] for c in r["dictionary"]],
           right={3, 4}, mono={1, 3, 4}, widths=(34, 20, 24, 24, 14, 58))

    # ---- 3 quality
    doc.add_page_break()
    q = r["quality"]
    _heading(doc, "03", "Data quality")
    intro = f"Health score {q['score']} ({q['grade']})."
    if q.get("before_version"):
        intro += f" 'Before' is version {q['before_version']}; 'after' is version {meta['version']}."
    doc.add_paragraph(intro)
    _table(doc, ["Measure", "Before", "After", "Change"],
           [[c["label"], c["before"], c["after"], c["change"] or "—"] for c in q["comparison"]], right={1, 2}, mono={1, 2})
    if q["deductions"]:
        doc.add_heading("Where the points went", level=2)
        _table(doc, ["Reason", "Points"], [[x["reason"], f"−{x['points']}"] for x in q["deductions"]], right={1}, mono={1})
    doc.add_heading("Open issues", level=2)
    if not q["issues"]:
        doc.add_paragraph("No open issues were detected in this version.")
    for issue in q["issues"]:
        p = doc.add_paragraph(style="List Bullet")
        _run(p, f"[{issue['severity']}] ", bold=True, color=WARN if issue["severity"] != "info" else MUTED)
        _run(p, issue["title"], bold=True)
        p = doc.add_paragraph()
        _run(p, issue["message"], color=MUTED, size=9.5)
        if issue.get("recommended"):
            _run(p, f"  Suggested fix: {issue['recommended']}", color=ACCENT, size=9.5)
    for note in q["notes"]:
        p = doc.add_paragraph()
        _run(p, note, color=MUTED, size=9)

    # ---- 4 cleaning log
    _heading(doc, "04", "Cleaning log")
    doc.add_paragraph(f"{r['cleaning']['count']} change(s) after upload. Each row is a saved version; none overwrote the original file.")
    if r["cleaning"]["pruned_note"]:
        p = doc.add_paragraph()
        _run(p, r["cleaning"]["pruned_note"], color=MUTED, size=9)
    _table(doc, ["Version", "What was done", "Cells changed", "Rows removed", "Shape after"],
           [[f"v{s['version']}", s["description"] + "".join(f"\n⚠ {w}" for w in s["warnings"]),
             s["cells_changed"], s["rows_removed"], f"{s['rows']} × {s['columns']}"] for s in r["cleaning"]["steps"]],
           right={2, 3, 4}, mono={0, 2, 3, 4}, widths=(16, 92, 22, 22, 22))

    # ---- 5 profiles
    doc.add_page_break()
    _heading(doc, "05", "Column profiles")
    for profile in r["profiles"]:
        p = doc.add_heading(level=2)
        _run(p, profile["name"])
        _run(p, f"   {profile['dtype']} · {profile['role']}", color=MUTED, size=9)
        rows = [[s[0], s[1]] for s in profile["stats"]]
        chart = profile.get("chart")
        if chart and chart["kind"] == "top_values":
            rows += [[f"  {b['label']}", f"{b['value']}"] for b in chart["bars"]]
        elif chart:
            rows += [[f"  {b['label']}", f"{b['value']} row(s)"] for b in chart["bars"]]
        _table(doc, ["Measure", "Value"], rows, right={1}, mono={1}, widths=(70, 104))
        for note in profile["notes"]:
            p = doc.add_paragraph()
            _run(p, note, color=MUTED, size=9)
    if r["profiles_omitted"]:
        p = doc.add_paragraph()
        _run(p, "Not profiled in detail: " + ", ".join(r["profiles_omitted"]) + ".", color=MUTED, size=9)

    # ---- 6 relationships
    _heading(doc, "06", "Relationships")
    rel = r["relationships"]
    if rel["pairs"]:
        _table(doc, ["Column A", "Column B", "r", "Strength", "Rows used"],
               [[x["a"], x["b"], x["r"], x["strength"], x["n"] + (" (small)" if x["small_sample"] else "")] for x in rel["pairs"]],
               right={2, 4}, mono={2, 4})
        if any(x["small_sample"] for x in rel["pairs"]):
            p = doc.add_paragraph()
            _run(p, "Pairs marked 'small' have fewer than 30 rows with both values: treat them as a hint, not evidence.", color=WARN, size=9)
    doc.add_paragraph(rel["note"])

    # ---- 7 recipe
    doc.add_page_break()
    _heading(doc, "07", "Reproduce it")
    doc.add_paragraph("This pandas script repeats every step above on the original file.")
    for line in r["recipe"].splitlines() or [""]:
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(0)
        _run(p, line or " ", mono=True, size=8)

    # ---- 8 methods
    _heading(doc, "08", "Methods and definitions")
    for item in r["methodology"]:
        p = doc.add_paragraph()
        _run(p, item["term"] + ". ", bold=True)
        _run(p, item["text"])

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()
